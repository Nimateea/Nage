export const GEMINI_MODEL = "gemini-3.8-flash";
const HOURLY_LIMIT = 60;
const BURST_LIMIT = 10;

/**
 * Checks live connectivity with Google Gemini API using gemini-3.8-flash.
 */
export async function testGeminiConnection(
  apiKeyCandidate?: string
): Promise<{ success: boolean; message: string; model: string }> {
  const key = apiKeyCandidate?.trim() || process.env.GEMINI_API_KEY;

  if (!key || key === "placeholder-gemini-api-key" || key.includes("placeholder")) {
    return {
      success: false,
      message: "No active GEMINI_API_KEY set. The Agent Generative Synthesizer is active.",
      model: GEMINI_MODEL,
    };
  }

  try {
    const client = new GoogleGenAI({ apiKey: key });
    const response = await client.models.generateContent({
      model: GEMINI_MODEL,
      contents: [
        {
          role: "user",
          parts: [{ text: "Hello Gemini, reply with 'OK' to confirm connectivity." }],
        },
      ],
      config: {
        maxOutputTokens: 20,
      },
    });

    if (response.text) {
      return {
        success: true,
        message: "Google Gemini 3.8 Flash is online and connected!",
        model: GEMINI_MODEL,
      };
    }

    return {
      success: false,
      message: "Gemini connected but returned an empty response.",
      model: GEMINI_MODEL,
    };
  } catch (err: unknown) {
    const errorMsg = err instanceof Error ? err.message : String(err);
    return {
      success: false,
      message: `Gemini API test failed: ${errorMsg}`,
      model: GEMINI_MODEL,
    };
  }
}

/**
 * Safely strips markdown code blocks and extracts valid JSON object from LLM response.
 */
function extractJsonFromText(rawText: string): Record<string, unknown> {
  const cleaned = rawText
    .replace(/^```json\s*/i, "")
    .replace(/^```\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim();

  try {
    return JSON.parse(cleaned);
  } catch {
    const firstBrace = cleaned.indexOf("{");
    const lastBrace = cleaned.lastIndexOf("}");
    if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
      return JSON.parse(cleaned.substring(firstBrace, lastBrace + 1));
    }
    throw new Error("Unable to parse JSON from AI response.");
  }
}

/**
 * Normalizes raw nodes generated by LLMs to guarantee 100% adherence to Nage CanvasNode schema.
 */
function normalizeAiNodes(
  rawNodes: unknown[],
  originX: number,
  originY: number
): CanvasNode[] {
  if (!Array.isArray(rawNodes)) return [];

  const normalized: CanvasNode[] = [];
  const frameMap = new Map<string, FrameNode>();

  for (const raw of rawNodes) {
    if (!raw || typeof raw !== "object") continue;
    const r = raw as Record<string, unknown>;

    const type = typeof r.type === "string" ? r.type : "rectangle";
    const id = typeof r.id === "string" && r.id.length > 0 ? r.id : nanoid();
    const name = typeof r.name === "string" ? r.name : `${type.charAt(0).toUpperCase() + type.slice(1)}`;
    const x = typeof r.x === "number" ? r.x : originX;
    const y = typeof r.y === "number" ? r.y : originY;
    const width = Math.max(10, typeof r.width === "number" ? r.width : 120);
    const height = Math.max(10, typeof r.height === "number" ? r.height : 60);

    if (type === "frame") {
      const frameNode: FrameNode = {
        id,
        name,
        type: "frame",
        x,
        y,
        width,
        height,
        visible: true,
        locked: false,
        opacity: 1,
        rotation: 0,
        cornerRadius: typeof r.cornerRadius === "number" ? r.cornerRadius : 16,
        fill: {
          type: "solid",
          color: (r.fill as { color?: string })?.color || "#0D0D0D",
          opacity: 1,
        },
        stroke: {
          color: (r.stroke as { color?: string })?.color || "#222222",
          width: typeof (r.stroke as { width?: number })?.width === "number" ? (r.stroke as { width?: number }).width! : 1,
          opacity: 1,
          style: "solid",
        },
        parentId: typeof r.parentId === "string" ? r.parentId : null,
        childIds: Array.isArray(r.childIds) ? (r.childIds as string[]) : [],
      };
      frameMap.set(id, frameNode);
      normalized.push(frameNode);
    } else if (type === "rectangle") {
      const rectNode: RectangleNode = {
        id,
        name,
        type: "rectangle",
        x,
        y,
        width,
        height,
        visible: true,
        locked: false,
        opacity: 1,
        rotation: 0,
        cornerRadius: typeof r.cornerRadius === "number" ? r.cornerRadius : 8,
        fill: {
          type: "solid",
          color: (r.fill as { color?: string })?.color || "#161616",
          opacity: 1,
        },
        stroke: {
          color: (r.stroke as { color?: string })?.color || "#2A2A2A",
          width: typeof (r.stroke as { width?: number })?.width === "number" ? (r.stroke as { width?: number }).width! : 1,
          opacity: 1,
          style: "solid",
        },
        parentId: typeof r.parentId === "string" ? r.parentId : null,
      };
      normalized.push(rectNode);
    } else if (type === "text") {
      const textNode: TextNode = {
        id,
        name,
        type: "text",
        x,
        y,
        width,
        height,
        visible: true,
        locked: false,
        opacity: 1,
        rotation: 0,
        content: typeof r.content === "string" ? r.content : "Text element",
        fontSize: typeof r.fontSize === "number" ? r.fontSize : 13,
        fontWeight: (r.fontWeight === 500 || r.fontWeight === 600 || r.fontWeight === 700 ? r.fontWeight : 400) as TextNode["fontWeight"],
        color: typeof r.color === "string" ? r.color : "#FFFFFF",
        textAlign: r.textAlign === "center" || r.textAlign === "right" ? r.textAlign : "left",
        parentId: typeof r.parentId === "string" ? r.parentId : null,
      };
      normalized.push(textNode);
    } else if (type === "ellipse") {
      const ellNode: EllipseNode = {
        id,
        name,
        type: "ellipse",
        x,
        y,
        width,
        height,
        visible: true,
        locked: false,
        opacity: 1,
        rotation: 0,
        fill: {
          type: "solid",
          color: (r.fill as { color?: string })?.color || "#2E5CFF",
          opacity: 1,
        },
        stroke: {
          color: (r.stroke as { color?: string })?.color || "transparent",
          width: 0,
          opacity: 0,
          style: "solid",
        },
        parentId: typeof r.parentId === "string" ? r.parentId : null,
      };
      normalized.push(ellNode);
    } else if (type === "line") {
      const x2 = typeof r.x2 === "number" ? r.x2 : x + width;
      const y2 = typeof r.y2 === "number" ? r.y2 : y;
      const lineNode: LineNode = {
        id,
        name,
        type: "line",
        x,
        y,
        x2,
        y2,
        width: Math.max(1, Math.abs(x2 - x)),
        height: Math.max(1, Math.abs(y2 - y)),
        visible: true,
        locked: false,
        opacity: 1,
        rotation: 0,
        stroke: {
          color: (r.stroke as { color?: string })?.color || "#222222",
          width: typeof (r.stroke as { width?: number })?.width === "number" ? (r.stroke as { width?: number }).width! : 1,
          opacity: 1,
          style: "solid",
        },
        parentId: typeof r.parentId === "string" ? r.parentId : null,
      };
      normalized.push(lineNode);
    } else if (type === "image") {
      const storagePath = typeof r.storagePath === "string" ? r.storagePath : "";
      const signedUrl = typeof r.signedUrl === "string" ? r.signedUrl : storagePath;
      const imgNode: ImageNode = {
        id,
        name,
        type: "image",
        x,
        y,
        width,
        height,
        visible: true,
        locked: false,
        opacity: 1,
        rotation: 0,
        storagePath,
        signedUrl,
        naturalWidth: typeof r.naturalWidth === "number" ? r.naturalWidth : width,
        naturalHeight: typeof r.naturalHeight === "number" ? r.naturalHeight : height,
        objectFit: r.objectFit === "fill" || r.objectFit === "contain" || r.objectFit === "cover" ? r.objectFit : "cover",
        parentId: typeof r.parentId === "string" ? r.parentId : null,
      };
      normalized.push(imgNode);
    }
  }

  // Ensure childIds on parent frames
  normalized.forEach((node) => {
    if (node.parentId && frameMap.has(node.parentId)) {
      const frame = frameMap.get(node.parentId)!;
      if (!frame.childIds.includes(node.id)) {
        frame.childIds.push(node.id);
      }
    }
  });

  return normalized;
}

/**
 * Checks rate limits for a given user ID using Supabase security definer RPC functions.
 */
async function verifyRateLimits(
  userId: string
): Promise<{ allowed: boolean; remaining: number }> {
  try {
    const admin = getSupabaseAdminClient();

    // 1. Check 1-minute burst limit
    const { data: burstAllowed } = await admin.rpc("check_rate_limit", {
      p_user_id: userId,
      p_action: "ai_generate",
      p_window_type: "burst",
      p_limit: BURST_LIMIT,
      p_duration: "1 minute",
    });

    if (burstAllowed === false) {
      return { allowed: false, remaining: 0 };
    }

    // 2. Check 1-hour quota limit
    const { data: hourlyAllowed } = await admin.rpc("check_rate_limit", {
      p_user_id: userId,
      p_action: "ai_generate",
      p_window_type: "hourly",
      p_limit: HOURLY_LIMIT,
      p_duration: "1 hour",
    });

    if (hourlyAllowed === false) {
      return { allowed: false, remaining: 0 };
    }

    // Query remaining quota
    const { data: remaining } = await admin.rpc("get_rate_limit_remaining", {
      p_user_id: userId,
      p_action: "ai_generate",
      p_window_type: "hourly",
      p_limit: HOURLY_LIMIT,
    });

    return { allowed: true, remaining: remaining ?? HOURLY_LIMIT };
  } catch (err) {
    console.warn("Rate limit check failed, allowing request gracefully:", err);
    return { allowed: true, remaining: HOURLY_LIMIT };
  }
}

/**
 * Logs generation request and outcome to public.ai_generation_logs
 */
async function logAiGeneration(
  userId: string | null,
  projectId: string | null,
  prompt: string,
  model: string,
  status: "pending" | "done" | "error"
) {
  if (!userId) return;
  try {
    const admin = getSupabaseAdminClient();
    await admin.from("ai_generation_logs").insert({
      user_id: userId,
      project_id: projectId,
      prompt,
      model,
      status,
    });
  } catch (err) {
    console.warn("Failed to log AI generation:", err);
  }
}

/**
 * Main AI generation agent powering Nage.
 */
export async function executeAiGeneration(
  req: AiGenerateRequest,
  userId: string | null
): Promise<AiGenerateResponse> {
  // 1. Rate limiting
  let remainingQuota = HOURLY_LIMIT;
  if (userId) {
    const rateCheck = await verifyRateLimits(userId);
    if (!rateCheck.allowed) {
      return {
        success: false,
        text: "Rate limit reached. You can generate up to 60 designs per hour (10 per minute). Please try again shortly.",
        error: "RATE_LIMIT_EXCEEDED",
        rateLimitRemaining: 0,
        rateLimitTotal: HOURLY_LIMIT,
      };
    }
    remainingQuota = rateCheck.remaining;
  }

  // Camera viewport positioning
  const zoom = req.camera?.zoom || 1;
  const originX = req.camera ? Math.round(-req.camera.x / zoom + 40) : 120;
  const originY = req.camera ? Math.round(-req.camera.y / zoom + 40) : 120;

  const candidateKey = req.apiKey?.trim() || process.env.GEMINI_API_KEY;
  const isRealApiKey =
    candidateKey &&
    candidateKey !== "placeholder-gemini-api-key" &&
    !candidateKey.includes("placeholder");

  // 2. Real Google Gemini 3.8 Flash API call
  if (isRealApiKey) {
    try {
      const client = new GoogleGenAI({ apiKey: candidateKey });

      let contextInfo = "";
      if (req.selectedNodes && req.selectedNodes.length > 0) {
        contextInfo = `\nSelected layers context:\n${JSON.stringify(
          req.selectedNodes.map((n) => ({
            id: n.id,
            name: n.name,
            type: n.type,
            x: n.x,
            y: n.y,
            width: n.width,
            height: n.height,
          }))
        )}`;
      }

      let promptWithPosition = `${req.prompt}\n(Target spawn coordinates on canvas: x=${originX}, y=${originY})${contextInfo}`;

      if (req.attachedScript) {
        promptWithPosition += `\n\n--- ATTACHED SCRIPT / SCREENPLAY ---\n${req.attachedScript}\n--- END SCRIPT ---`;
      }

      type GeminiPart = { text: string } | { inlineData: { mimeType: string; data: string } };
      const parts: GeminiPart[] = [];

      // Multimodal image reference support
      if (req.attachedImage && req.attachedImage.startsWith("data:")) {
        const match = req.attachedImage.match(/^data:([^;]+);base64,(.+)$/);
        if (match) {
          parts.push({
            inlineData: {
              mimeType: match[1],
              data: match[2],
            },
          });
        }
      }

      parts.push({ text: promptWithPosition });

      const response = await client.models.generateContent({
        model: GEMINI_MODEL,
        contents: [
          {
            role: "user",
            parts,
          },
        ],
        config: {
          systemInstruction: NAGE_AI_SYSTEM_INSTRUCTION,
          responseMimeType: "application/json",
          temperature: 0.7,
        },
      });

      const responseText = response.text || "{}";
      const parsed = extractJsonFromText(responseText);

      const reply = typeof parsed.reply === "string" ? parsed.reply : "Generated design components.";
      const rawNodes = Array.isArray(parsed.nodes) ? (parsed.nodes as unknown[]) : [];
      const normalizedNodes = normalizeAiNodes(rawNodes, originX, originY);

      await logAiGeneration(
        userId,
        req.projectId ?? null,
        req.prompt,
        GEMINI_MODEL,
        "done"
      );

      return {
        success: true,
        text: reply,
        generatedNodes: normalizedNodes.length > 0 ? normalizedNodes : undefined,
        rateLimitRemaining: remainingQuota,
        rateLimitTotal: HOURLY_LIMIT,
      };
    } catch (err: unknown) {
      console.warn("Gemini API call failed, falling back to agent design synthesizer:", err);
      await logAiGeneration(
        userId,
        req.projectId ?? null,
        req.prompt,
        GEMINI_MODEL,
        "error"
      );
    }
  }

  // 3. Fallback Agentic Design Synthesizer (synthesizes whatever the user typed!)
  const agentOutput = generateAgentDesign(
    req.prompt,
    req.task,
    req.camera,
    req.attachedImage,
    req.attachedScript
  );

  await logAiGeneration(
    userId,
    req.projectId ?? null,
    req.prompt,
    "agentic-design-synthesizer",
    "done"
  );

  return {
    success: true,
    text: agentOutput.reply,
    generatedNodes: agentOutput.nodes,
    rateLimitRemaining: remainingQuota,
    rateLimitTotal: HOURLY_LIMIT,
  };
}
